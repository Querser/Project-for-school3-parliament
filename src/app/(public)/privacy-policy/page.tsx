import type { Metadata } from "next";

import { SectionTitle } from "@/components/public/section-title";
import { Card } from "@/components/shared/card";
import { getStaticPageByKey } from "@/features/pages/service";
import { STATIC_PAGE_KEYS } from "@/lib/constants";

export const metadata: Metadata = {
  title: "Политика конфиденциальности",
  description: "Правила обработки персональных данных на сайте ученического парламента.",
};

const defaultPrivacyPolicyContent = `
На сайте ученического парламента МОУ СОШ №3 г. Можайска обрабатываются только те данные, которые необходимы для работы с инициативами учащихся и обратной связи.

1. Какие данные могут собираться:
- ФИО, класс, контактные данные, текст инициативы и вложения из формы «Инициативы».
- Технические данные запроса: IP-адрес, user-agent, служебные идентификаторы.
- Обезличенные аналитические события для оценки работы разделов сайта.

2. Для чего это нужно:
- Рассмотрение инициатив и подготовка ответа заявителю.
- Уточнение деталей инициативы при необходимости.
- Обеспечение безопасности и стабильной работы сайта.

3. Кто имеет доступ:
- Только уполномоченные представители ученического парламента и администраторы сайта в рамках своих обязанностей.
- Контактные данные используются исключительно для коммуникации по отправленной инициативе.

4. Хранение и защита:
- Данные хранятся в защищенной информационной системе школы.
- Срок хранения ограничен периодом, необходимым для достижения целей обработки и выполнения требований локальных нормативных актов.

5. Права пользователя:
- Вы можете запросить уточнение, исправление или актуализацию переданных данных.
- Вы можете обратиться по вопросам обработки персональных данных через официальные контакты школы и ученического парламента.

Отправляя инициативу через сайт, вы подтверждаете согласие на обработку персональных данных в объеме, необходимом для рассмотрения обращения.
`;

export default async function PrivacyPolicyPage() {
  const pageData = await getStaticPageByKey(STATIC_PAGE_KEYS.privacyPolicy).catch(() => null);

  return (
    <div className="space-y-6">
      <SectionTitle title={pageData?.title ?? "Политика конфиденциальности"} />
      <Card>
        <article className="whitespace-pre-line leading-relaxed text-slate-700">
          {pageData?.content ?? defaultPrivacyPolicyContent}
        </article>
      </Card>
    </div>
  );
}
